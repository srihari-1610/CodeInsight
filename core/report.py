"""Export an analysis as Markdown or JSON."""
from __future__ import annotations

import json
from dataclasses import asdict

from .analyzer import AnalysisResult

_FENCE = {"Python": "python", "C++": "cpp", "Java": "java"}


def to_json(result: AnalysisResult) -> str:
    return json.dumps(
        {"request": asdict(result.request), "analysis": asdict(result.analysis), "model": result.model},
        indent=2,
    )


def to_markdown(result: AnalysisResult) -> str:
    a, r, cx = result.analysis, result.request, result.analysis.complexity
    fence = _FENCE.get(r.language, "")
    lines = [
        f"# CodeInsight report: {a.algorithm}",
        "",
        f"- **Language:** {r.language}",
        f"- **Category:** {a.category}  |  **Tags:** {', '.join(a.tags) or '-'}",
        f"- **Time:** {cx.time}  |  **Space:** {cx.space}",
        "",
        "## Summary",
        a.summary,
        "",
        "## Code",
        f"```{fence}",
        r.code,
        "```",
        "",
        "## Line-by-line explanation",
    ]
    for b in a.line_blocks:
        span = f"{b.start_line}" if b.start_line == b.end_line else f"{b.start_line}-{b.end_line}"
        lines.append(f"- **Lines {span}:** {b.explanation}" + (f" _Insight: {b.key_insight}_" if b.key_insight else ""))
    lines += ["", "## Complexity", f"- Time: `{cx.time}`", f"- Space: `{cx.space}`", f"- Operation model: `{cx.ops_expression}`"]
    if cx.best_case:
        lines.append(f"- Best case: {cx.best_case}")
    if cx.worst_case:
        lines.append(f"- Worst case: {cx.worst_case}")
    lines += ["", cx.derivation, "", "## Optimizations"]
    if not a.optimizations:
        lines.append("No significant optimizations found.")
    for o in a.optimizations:
        lines += [f"### {o.title} ({o.impact} impact)", f"- Bottleneck: {o.bottleneck}", f"- Suggestion: {o.suggestion}", f"- Trade-off: {o.tradeoff}"]
        if o.optimized_code:
            lines += [f"```{fence}", o.optimized_code, "```"]
    lines += ["", "## Pitfalls"]
    lines += [f"- [{p.kind}]{f' (line {p.line})' if p.line else ''} {p.description}" for p in a.pitfalls] or ["None flagged."]
    q = a.quality
    lines += ["", "## Quality", f"- Clarity: {q.clarity_score}/10", f"- Naming: {q.naming_feedback}", f"- Structure: {q.structure_feedback}"]
    lines += [f"- Tip: {t}" for t in q.tips]
    lines += ["", f"_Generated by CodeInsight ({result.model}, {result.mode} mode)._", ""]
    return "\n".join(lines)
